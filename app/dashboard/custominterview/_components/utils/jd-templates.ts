export const getJDTemplate = (
  interviewType: string,
  subType?: string
): string => {
  if (interviewType === 'Technical') {
    switch (subType) {
      case 'python-developer':
        return JD_TEMPLATES.technical.python
      case 'full-stack-developer':
        return JD_TEMPLATES.technical['full-stack-developer']
      case 'react-developer':
        return JD_TEMPLATES.technical['react-developer']
      case 'frontend-developer':
        return JD_TEMPLATES.technical['frontend-developer']
    }
  } else if (interviewType === 'General' && subType === 'UPSE') {
    return JD_TEMPLATES.general.upse
  } else if (interviewType === 'Foreign Language') {
    switch (subType) {
      case 'English':
        return JD_TEMPLATES['foreign-language'].english
      case 'Spanish':
        return JD_TEMPLATES['foreign-language'].spanish
      case 'French':
        return JD_TEMPLATES['foreign-language'].french
      case 'German':
        return JD_TEMPLATES['foreign-language'].german
      default:
        return JD_TEMPLATES['foreign-language'].english
    }
  } else if (interviewType === 'HR') {
    switch (subType) {
      case 'Behavioral':
        return JD_TEMPLATES.hr.behavioral
      case 'Situational':
        return JD_TEMPLATES.hr.situational
      case 'CompetencyBased':
        return JD_TEMPLATES.hr.competencyBased
      case 'CaseStudy':
        return JD_TEMPLATES.hr.caseStudy
    }
  }

  // No default templates - only return available templates
  return ''
}
